def _stage_records(run: PackRun, plan_after: int) -> list[dict[str, str]]:
    """The escrow chain's records after the ``plan_after``-th one: what the
    chain says happened to the plans since."""
    world = run.world
    assert world.mandate is not None
    chain = world.binder.engine(world.mandate.mandate_id).engine.chain
    return [
        {"type": r.record_type.value, "plan": str(r.plan_id), "note": r.note}
        for r in list(chain.records())[plan_after:]
    ]


def _chain_length(run: PackRun) -> int:
    world = run.world
    assert world.mandate is not None
    return len(world.binder.engine(world.mandate.mandate_id).engine.chain.records())


def _reconcile(run: PackRun, since: str) -> dict[str, Any]:
    world = run.world
    repository: Repository = world.system
    assert world.mandate is not None
    chain = world.binder.engine(world.mandate.mandate_id).engine.chain
    found = GIT.reconcile_git(repository.current, chain.records(), since=since)
    return {
        "since": since,
        "commits": found.writes_checked,
        "stages": found.stages_checked,
        "clean": found.clean,
        "unmediated": [
            {"commit": w.primary_key, "what": w.operation, "by": w.actor, "at": w.at}
            for w in found.unmediated
        ],
        "findings": [f.describe() for f in found.stages],
    }


def _bump_arguments(repository: Repository, version: str) -> dict[str, str]:
    files = bumped(repository.files(), "httpx", version)
    return {
        "base": repository.head(),
        "manifest": files["pyproject.toml"],
        "lock": files["uv.lock"],
        "matrix": files[".github/workflows/ci.yml"],
    }


