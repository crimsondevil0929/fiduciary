def _git(cwd: Path, *args: str, stdin: bytes | None = None, env: Mapping[str, str] = {}) -> str:
    done = subprocess.run(  # noqa: S603 - an argument list
        [shutil.which("git") or "git", "-c", "core.hooksPath=/dev/null", *args],
        cwd=cwd,
        input=stdin,
        capture_output=True,
        check=True,
        env={"PATH": "/usr/bin:/bin:/usr/local/bin", "GIT_CONFIG_NOSYSTEM": "1", **env},
    )
    return done.stdout.decode().strip()


