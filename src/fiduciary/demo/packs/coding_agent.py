@dataclass
class Repository:
    """The repository the acts work on, and the substrate's handles to it."""

    origin: Path
    base: str
    hooks: tuple[Any, ...]
    control: Path
    on_measured: Callable[[], None] | None = None
    """Called once, after the next stage's measurement: a push at that moment."""
    pushes: list[str] = field(default_factory=list)
    current: Any = None
    """The substrate the lineage's engine runs on, once it is built."""

    def head(self) -> str:
        return _git(self.origin, "rev-parse", f"refs/heads/{BRANCH}")

    def show(self, path: str, rev: str = BRANCH) -> str:
        return _git(self.origin, "show", f"{rev}:{path}") + "\n"

    def files(self) -> dict[str, str]:
        return {
            "m": self.show("pyproject.toml"),
            "l": self.show("uv.lock"),
            "w": self.show(".github/workflows/ci.yml"),
        }

    def substrate(self) -> Any:
        assert GIT is not None
        inner = GIT.GitSubstrate(
            self.origin,
            branch=BRANCH,
            workspace=REPO,
            hooks=self.hooks,
            control=self.control,
            author=("repo-maintainer-agent", "agent@acme.example"),
        )
        self.current = inner
        return _Racing(inner, self)

    def push(self, path: str, text: str, message: str) -> str:
        """A teammate's commit on ``main``, pushed straight to it: no stage,
        no trailer."""
        parent = self.head()
        blob = _git(self.origin, "hash-object", "-w", "--stdin", stdin=text.encode())
        index = self.origin.parent / "push.index"
        env = {**AUTHOR, "GIT_INDEX_FILE": str(index)}
        _git(self.origin, "read-tree", parent, env=env)
        _git(self.origin, "update-index", "--add", "--cacheinfo", f"100644,{blob},{path}", env=env)
        tree = _git(self.origin, "write-tree", env=env)
        index.unlink(missing_ok=True)
        commit = _git(self.origin, "commit-tree", tree, "-p", parent, "-m", message, env=env)
        _git(self.origin, "update-ref", f"refs/heads/{BRANCH}", commit, parent)
        self.pushes.append(commit)
        return commit

    def fingerprint(self) -> str:
        return hashlib.sha256(_git(self.origin, "for-each-ref").encode()).hexdigest()


class _Racing:
    """The Git substrate, with the one moment the race act needs: just after a
    stage is measured, a teammate's push (:attr:`Repository.on_measured`)."""

    def __init__(self, inner: Any, repository: Repository) -> None:
        self._inner = inner
        self._repository = repository

    def __getattr__(self, name: str) -> Any:
        return getattr(self._inner, name)

    def diff(self, handle: Any) -> Any:
        found = self._inner.diff(handle)
        hook, self._repository.on_measured = self._repository.on_measured, None
        if hook is not None:
            hook()
        return found


def _system(root: Path, control: Path) -> tuple[Callable[[], Any], Repository]:
    """The repository: a bare origin with one commit, its code generator, and
    the control database the substrate keeps its outbox, inbox and windows in."""
    assert GIT is not None
    root, control = root.resolve(), control.resolve()
    seed = root / "repository-seed"
    origin = root / f"{REPO}.git"
    seed.mkdir()
    for path, text in FILES.items():
        target = seed / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    subprocess.run([sys.executable, "tools/codegen.py"], cwd=seed, check=True, capture_output=True)
    _git(seed, "init", "-q", "-b", BRANCH)
    _git(seed, "add", "-A")
    _git(seed, "commit", "-q", "-m", "billing-service 2.3.0", env=AUTHOR)
    _git(root, "clone", "-q", "--bare", str(seed), str(origin))
    shutil.rmtree(seed)
    hooks = (
        GIT.GitHook(
            "codegen",
            (sys.executable, "tools/codegen.py"),
            when=(SCHEMA,),
            sources=("tools/codegen.py",),
        ),
    )
    repository = Repository(origin, _git(origin, "rev-parse", BRANCH), hooks, control)
    (root / "git-substrate.json").write_text(
        json.dumps(
            {
                "repository": str(origin),
                "branch": f"refs/heads/{BRANCH}",
                "workspace": REPO,
                "control": str(control),
                "classes": {c.name: list(c.patterns) for c in GIT.DEFAULT_CLASSES},
                "hooks": [
                    {
                        "name": h.name,
                        "argv": list(h.argv),
                        "when": list(h.when),
                        "sources": list(h.sources),
                    }
                    for h in hooks
                ],
            },
            indent=2,
        )
        + "\n"
    )
    return repository.substrate, repository


def _fingerprint(world: Any) -> str:
    repository: Repository = world.system
    return repository.fingerprint()


