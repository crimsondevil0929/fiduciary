"""Coding agents: a repository maintainer agent, on a real Git branch.

The one pack whose stage is not SQL. Each call's plan runs in a worktree of
its own at the head of ``main``, on interlock's Git substrate
(:mod:`interlock.git_substrate`): the agent's edits, then the repository's
code generator, then a measurement of every file that changed, read from
Git's own index. A plan that passes commits with a compare-and-swap of
``main`` from the head it was measured on; a push that lands meanwhile leaves
``main`` where the push put it, and the plan uncommitted. The control
database beside the repository (the back office of every other pack) holds
the outbox, the inbox and the window history.

The repository came with what repositories come with:

- ``codegen``: a hook that rewrites the 35 client modules under
  ``src/billing/clients/`` whenever the API schema changes;
- workflows that publish to PyPI with ``secrets.PYPI_TOKEN``;
- a CI system that answers a run request with signed ``ci.checks_passed``
  webhooks naming the exact bytes it tested.

Each path's class is its table (``src``, ``tests``, ``docs``, ``deps``,
``workflows``, ``governance``, ``infra``, ``other``) and the repository is
its partition. The mandate grants ``src``, ``tests`` and ``docs``, and
``deps`` only with CI's word for the bytes. interlock's configuration file
names SQLite and PostgreSQL substrates only, so this pack writes
``git-substrate.json`` in place of ``fiduciary.toml``.
"""

