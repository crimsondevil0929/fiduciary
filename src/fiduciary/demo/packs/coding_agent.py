class Ci:
    """A stand-in for the CI system: runs the suite on ``main`` with the
    dependency bumped, and reports each file it tested by its blob id."""

    def __init__(self, repository: Repository) -> None:
        self._repository = repository
        self.runs: list[dict[str, Any]] = []
        self.webhooks: list[tuple[str, dict[str, Any]]] = []

    def send(self, delivery: Delivery) -> DeliveryResult:
        payload = json.loads(delivery.payload)
        run_id = "run_" + hashlib.sha256(delivery.idempotency_key.encode()).hexdigest()[:16]
        tested = bumped(self._repository.files(), payload["package"], payload["version"])
        self.runs.append({"run_id": run_id, **payload, "head": self._repository.head()})
        for path in ("pyproject.toml", "uv.lock"):
            event = {
                "type": "ci.checks_passed",
                "data": {
                    "run_id": run_id,
                    "path": path,
                    "blob_sha": blob_sha(tested[path]),
                    "conclusion": "success",
                },
            }
            self.webhooks.append((f"evt_{run_id}_{len(self.webhooks)}", event))
        return DeliveryResult(DELIVERED, status_code=201, remote_ref=run_id)


def webhook(
    event: Mapping[str, Any], event_id: str, key: bytes = CI_KEY
) -> tuple[dict[str, str], bytes]:
    """A Standard Webhooks request, signed as the CI system signs."""
    body = json.dumps(event).encode()
    stamp = str(int(time.time()))
    signature = base64.b64encode(
        hmac.new(key, f"{event_id}.{stamp}.".encode() + body, "sha256").digest()
    ).decode()
    headers = {
        "Content-Type": "application/json",
        "webhook-id": event_id,
        "webhook-timestamp": stamp,
        "webhook-signature": f"v1,{signature}",
    }
    return headers, body


def run_ci(run: PackRun, ci: Ci) -> list[dict[str, Any]]:
    """Deliver the CI requests the outbox holds, then take each signed webhook
    CI sends back, and one forged one, through the inbox."""
    world = run.world
    store = SqliteOutboxStore(str(world.back_office), writes=RELAY)
    relay = Relay(
        store,
        adapters={"ci": ci},
        breaker=LedgerBreaker(world.governor),
        signer=world.signers["relay-b"],
        relay_id="relay-b",
        lease=timedelta(milliseconds=800),
        timeout=timedelta(milliseconds=300),
    )
    try:
        for _ in range(20):
            if not relay.run_once(limit=10):
                break
    finally:
        store.close()
    relays = Keyring({world.key_id("relay-b"): world.signers["relay-b"].public_key()})
    inbox_store = SqliteOutboxStore(str(world.back_office), writes=INBOX)
    answers = []
    try:
        inbox = Inbox(
            inbox_store,
            (CI_SOURCE,),
            signer=world.signers["inbox"],
            relays=relays,
            secrets={CI_SECRET_ENV: CI_SECRET}.get,
        )
        for event_id, event in ci.webhooks:
            answer = inbox.receive("ci", *webhook(event, event_id))
            answers.append(
                {"event": event_id, "path": event["data"]["path"], "status": answer.status}
            )
        if ci.webhooks:
            event_id, event = ci.webhooks[-1]
            forged = {**event, "data": {**event["data"], "blob_sha": "0" * 40}}
            answer = inbox.receive("ci", *webhook(forged, event_id + "_forged", key=b"guess" * 8))
            answers.append(
                {"event": event_id + "_forged", "path": "uv.lock", "status": answer.status}
            )
    finally:
        inbox_store.close()
    return answers


