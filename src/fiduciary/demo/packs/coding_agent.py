def bumped(files: Mapping[str, str], package: str, version: str) -> dict[str, str]:
    """``pyproject.toml``, ``uv.lock`` and the CI matrix with ``package`` at
    ``version``: what CI tests, and what the agent's bump writes."""
    manifest = re.sub(rf'"{re.escape(package)}==[^"]+"', f'"{package}=={version}"', files["m"])
    lock = re.sub(
        rf'(name = "{re.escape(package)}"\nversion = )"[^"]+"', rf'\g<1>"{version}"', files["l"]
    )
    matrix = re.sub(rf'{re.escape(package)}: \["[^"]+"\]', f'{package}: ["{version}"]', files["w"])
    return {"pyproject.toml": manifest, "uv.lock": lock, ".github/workflows/ci.yml": matrix}


def blob_sha(text: str) -> str:
    """The id Git gives a file holding ``text``."""
    data = text.encode("utf-8")
    return hashlib.sha1(b"blob %d\0" % len(data) + data, usedforsecurity=False).hexdigest()


