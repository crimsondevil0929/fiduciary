"""The order on mandates (``docs/FIDUCIARY_SPEC.md`` §5.1, §5.2), by property.

Mandates are generated by narrowing a wide one at random, every narrowing
kept valid. The properties: ⊑ is reflexive (F5-1); every generated
narrowing refines what it narrowed, and so, transitively, every ancestor; and
every single-field widening of a mandate is named at exactly that field.
"""

