def _widened(raw: Raw, index: int) -> tuple[str, Raw] | None:
    prefix, applies, widen = WIDENINGS[index]
    if not applies(raw):
        return None
    wider = copy.deepcopy(raw)
    widen(wider)
    try:
        parse(wider)
    except MalformedError:
        return None
    return prefix, wider


@settings(max_examples=300, deadline=None, suppress_health_check=[HealthCheck.too_slow])
@given(
    seeds,
    st.integers(min_value=0, max_value=40),
    st.integers(min_value=0, max_value=len(WIDENINGS) - 1),
)
def test_every_single_field_widening_is_named_at_its_field(
    seed: int, steps: int, index: int
) -> None:
    raw = narrow(universe(), random.Random(seed), steps)
    found = _widened(raw, index)
    if found is None:
        return
    prefix, wider = found
    problems = refines(parse(wider), parse(raw))
    assert problems, f"widening {prefix} went unnoticed"
    assert all(p.path.startswith(prefix) for p in problems), (prefix, [str(p) for p in problems])


@pytest.mark.parametrize("index", range(len(WIDENINGS)))
def test_each_widening_applies_to_the_wide_mandate_or_a_narrowing_of_it(index: int) -> None:
    """Every widening above is exercised: it applies to the wide mandate, or
    to one of a fixed set of its narrowings."""
    for seed in range(200):
        raw = universe() if seed == 0 else narrow(universe(), random.Random(seed), 25)
        found = _widened(raw, index)
        if found is not None:
            prefix, wider = found
            problems = refines(parse(wider), parse(raw))
            assert problems and all(p.path.startswith(prefix) for p in problems), (prefix, problems)
            return
    pytest.fail(f"widening {WIDENINGS[index][0]} never applied")


