Widening = tuple[str, Callable[[Raw], bool], Callable[[Raw], None]]


def _granting_above_revoke(raw: Raw) -> str | None:
    q = raw["roster"]["quorums"]
    for name in (*GRANTING, "accept_repair"):
        floor = 1 if name == "accept_repair" else q["revoke"]
        if q[name] > floor:
            return name
    return None


def _sink_op_free(raw: Raw) -> bool:
    return (
        "stripe" in raw["outbound"]["sinks"]
        and "charges.create" not in raw["outbound"]["sinks"]["stripe"]["operations"]
    )


def _caps(raw: Raw) -> list[Raw]:
    allowed = {(s, op) for s, b in raw["outbound"]["sinks"].items() for op in b["operations"]}
    return [c for c in raw["outbound"]["caps"] if (c["sink"], c["operation"]) in allowed]


def _recipients(raw: Raw) -> list[Raw]:
    allowed = {(s, op) for s, b in raw["outbound"]["sinks"].items() for op in b["operations"]}
    return [r for r in raw["outbound"]["recipients"] if (r["sink"], r["operation"]) in allowed]


def _bump_money(value: str, by: str = "1") -> str:
    return _money(_dec(value) + _dec(by))


