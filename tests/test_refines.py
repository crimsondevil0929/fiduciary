Edit = Callable[[Raw, random.Random], None]


def _shrink_int(value: int, rnd: random.Random, floor: int = 1) -> int:
    return rnd.randint(min(floor, value), value)


def _drop_one(items: list[Any], rnd: random.Random, keep: int = 1) -> None:
    if len(items) > keep:
        items.pop(rnd.randrange(len(items)))


def n_term(raw: Raw, rnd: random.Random) -> None:
    raw["term"]["not_before"] = (
        "2026-10-20T00:00:00.000000Z" if rnd.random() < 0.5 else raw["term"]["not_before"]
    )
    raw["term"]["not_after"] = (
        "2026-12-01T00:00:00.000000Z" if rnd.random() < 0.5 else raw["term"]["not_after"]
    )


def n_roster(raw: Raw, rnd: random.Random) -> None:
    roster = raw["roster"]
    q = roster["quorums"]
    if rnd.random() < 0.3 and max(q.values()) < len(roster["principals"]):
        _drop_one(roster["principals"], rnd)
    size = len(roster["principals"])
    name = rnd.choice([*GRANTING, "accept_repair"])
    q[name] = rnd.randint(q[name], size)
    if rnd.random() < 0.3:
        q["reduce"] = 1


def n_budget(raw: Raw, rnd: random.Random) -> None:
    budget = raw["budget"]
    per_call = _dec(budget["per_call"])
    floor = max(per_call, _dec(raw["delegation"]["envelope"]) if raw["delegation"] else Decimal(0))
    envelope = _dec(budget["envelope"])
    budget["envelope"] = _money(max(floor, envelope * Decimal(rnd.randint(50, 100)) / 100))
    budget["per_call"] = _money(
        max(Decimal("0.00000001"), per_call * Decimal(rnd.randint(50, 100)) / 100)
    )
    budget["max_output_tokens"] = _shrink_int(budget["max_output_tokens"], rnd)
    _drop_one(budget["models"], rnd)


def n_governance(raw: Raw, rnd: random.Random) -> None:
    g = raw["governance"]
    g["max_calls"] = _shrink_int(g["max_calls"], rnd)
    g["seconds"] = rnd.randint(g["seconds"], g["seconds"] + 600)
    g["fleet_velocity"] = g["fleet_velocity"] or rnd.random() < 0.5
    c = g["cognitive"]
    for key in ("max_identical_repeats", "max_similar_streak", "min_cycle_repeats"):
        c[key] = _shrink_int(c[key], rnd)
    for key in ("similarity_threshold", "result_similarity_threshold"):
        c[key] = _spell(_dec(c[key]) * Decimal(rnd.randint(50, 100)) / 100)
    c["max_cycle_period"] = rnd.randint(c["max_cycle_period"], c["max_cycle_period"] + 3)
    c["min_novelty_ratio"] = _spell(
        min(Decimal(1), _dec(c["min_novelty_ratio"]) + Decimal(rnd.randint(0, 5)) / 100)
    )


def n_data(raw: Raw, rnd: random.Random) -> None:
    d = raw["data"]
    guarded = {g["table"] for g in d["drawdown"]}
    droppable = [t for t in d["tables"] if t not in guarded]
    if len(d["tables"]) > 1 and droppable and rnd.random() < 0.3:
        del d["tables"][rnd.choice(droppable)]
    table = rnd.choice(sorted(d["tables"]))
    _drop_one(d["tables"][table], rnd)
    if isinstance(d["tenants"], list):
        _drop_one(d["tenants"], rnd, keep=0)
    d["declared_tenants"] = d["declared_tenants"] or rnd.random() < 0.5
    d["max_rows"] = _shrink_int(d["max_rows"], rnd)
    d["max_tenants"] = _shrink_int(d["max_tenants"], rnd)
    for guard in d["drawdown"]:
        guard["max_drop"] = _spell(_dec(guard["max_drop"]) * Decimal(rnd.randint(50, 100)) / 100)
    if d["stated_footprint"] is None:
        d["stated_footprint"] = {"tolerance": "4", "blocking": True}
    else:
        f = d["stated_footprint"]
        f["tolerance"] = _spell(_dec(f["tolerance"]) * Decimal(rnd.randint(50, 100)) / 100)
        f["blocking"] = f["blocking"] or rnd.random() < 0.5
    if not d["facts"] and rnd.random() < 0.3:
        d["facts"] = [
            {
                "kind": ["charge.refunded"],
                "field": "amount",
                "table": "refunds",
                "column": "amount",
                "key": None,
                "exempt": [],
            }
        ]


def n_outbound(raw: Raw, rnd: random.Random) -> None:
    o = raw["outbound"]
    if len(o["sinks"]) > 1 and rnd.random() < 0.3:
        sink = rnd.choice(sorted(o["sinks"]))
        del o["sinks"][sink]
        o["per_sink"].pop(sink, None)
        o["caps"] = [c for c in o["caps"] if c["sink"] != sink]
        o["recipients"] = [r for r in o["recipients"] if r["sink"] != sink]
        if o["tenants"] is not None:
            o["tenants"]["fields"].pop(sink, None)
    for name, bounds in o["sinks"].items():
        used = {c["operation"] for c in o["caps"] if c["sink"] == name} | {
            r["operation"] for r in o["recipients"] if r["sink"] == name
        }
        droppable = [op for op in bounds["operations"] if op not in used]
        if len(bounds["operations"]) > 1 and droppable and rnd.random() < 0.5:
            bounds["operations"].remove(rnd.choice(droppable))
        for key in ("max_attempts", "not_after_seconds", "max_payload_bytes"):
            bounds[key] = _shrink_int(bounds[key], rnd)
    o["max_per_plan"] = (
        _shrink_int(o["max_per_plan"], rnd, 0) if o["max_per_plan"] is not None else 10
    )
    for sink in o["per_sink"]:
        o["per_sink"][sink] = _shrink_int(o["per_sink"][sink], rnd, 0)
    for cap in o["caps"]:
        if isinstance(cap["maximum"], dict):
            if len(cap["maximum"]) > 1 and rnd.random() < 0.3:
                del cap["maximum"][rnd.choice(sorted(cap["maximum"]))]
            for currency in cap["maximum"]:
                cap["maximum"][currency] = _spell(
                    _dec(cap["maximum"][currency]) * Decimal(rnd.randint(50, 100)) / 100
                )
    for rule in o["recipients"]:
        _drop_one(rule["domains"], rnd)
        rule["subdomains"] = rule["subdomains"] and rnd.random() < 0.5
        if "to.*.email" not in rule["fields"] and rnd.random() < 0.3:
            rule["fields"] = sorted([*rule["fields"], "to.*.email"])
    if o["tenants"] is not None:
        t = o["tenants"]
        t["max_tenants"] = _shrink_int(t["max_tenants"], rnd)
        t["require_tenant"] = t["require_tenant"] or rnd.random() < 0.5


def n_tools(raw: Raw, rnd: random.Random) -> None:
    raw["tools"]["statements"] = "bound" if rnd.random() < 0.5 else raw["tools"]["statements"]
    _drop_one(raw["tools"]["bindings"], rnd, keep=0)


def n_recovery(raw: Raw, rnd: random.Random) -> None:
    r = raw["recovery"]
    if r is None:
        return
    if rnd.random() < 0.15:
        raw["recovery"] = None
        return
    step = _dec(r["step_estimate"]) * Decimal(rnd.randint(50, 100)) / 100
    r["step_estimate"] = _money(max(Decimal("0.00000001"), step))
    r["reserve"] = _money(
        max(_dec(r["step_estimate"]), _dec(r["reserve"]) * Decimal(rnd.randint(50, 100)) / 100)
    )
    r["max_steps"] = _shrink_int(r["max_steps"], rnd)
    for directive in r["directives"]:
        _drop_one(directive["answers"], rnd)
    if "thrashing" not in r["revoke_on"] and rnd.random() < 0.5:
        r["revoke_on"] = sorted([*r["revoke_on"], "thrashing"])
    if r["revocable"] is not None and "poll" not in r["revocable"] and rnd.random() < 0.5:
        r["revocable"] = sorted([*r["revocable"], "poll"])
    if r["token_ceiling"] is not None:
        r["token_ceiling"] = _shrink_int(r["token_ceiling"], rnd)
    r["guidance"] = r["guidance"] and rnd.random() < 0.5


def n_extension(raw: Raw, rnd: random.Random) -> None:
    x = raw["extension"]
    if x is None:
        return
    if rnd.random() < 0.15 and not any(
        rule["resolution"] == "grant" for rule in raw["escalation"]["auto"]
    ):
        raw["extension"] = None
        return
    auto = x["auto"]
    floor = _dec(auto["max_grant"]) if auto else Decimal("0.00000001")
    x["max_grant"] = _money(max(floor, _dec(x["max_grant"]) * Decimal(rnd.randint(50, 100)) / 100))
    x["max_total"] = _money(
        max(
            _dec(x["max_grant"]),
            _dec(auto["max_total"]) if auto else Decimal(0),
            _dec(x["max_total"]) * Decimal(rnd.randint(50, 100)) / 100,
        )
    )
    x["margin"] = _spell(_dec(x["margin"]) * Decimal(rnd.randint(50, 100)) / 100)
    x["ttl_seconds"] = _shrink_int(x["ttl_seconds"], rnd)


def n_escalation(raw: Raw, rnd: random.Random) -> None:
    s = raw["escalation"]
    s["max_open"] = _shrink_int(s["max_open"], rnd, 0)
    s["ttl_seconds"] = _shrink_int(s["ttl_seconds"], rnd)
    if s["auto"] and rnd.random() < 0.3:
        _drop_one(s["auto"], rnd, keep=0)
    for rule in s["auto"]:
        when = rule["when"]
        for key in ("max_dropped", "max_requeues"):
            if key in when:
                when[key] = _shrink_int(when[key], rnd, 0)
        for key in ("causes", "outcome"):
            if key in when:
                _drop_one(when[key], rnd, keep=0)
        if rule["class"] == "refused":
            when["exhaustive"] = bool(when.get("exhaustive")) or rnd.random() < 0.5


def n_delegation(raw: Raw, rnd: random.Random) -> None:
    d = raw["delegation"]
    if d is None:
        return
    if rnd.random() < 0.15:
        raw["delegation"] = None
        return
    d["max_depth"] = _shrink_int(d["max_depth"], rnd, 0)
    d["max_children"] = _shrink_int(d["max_children"], rnd, 0)
    d["envelope"] = _money(
        max(Decimal("0.00000001"), _dec(d["envelope"]) * Decimal(rnd.randint(50, 100)) / 100)
    )


NARROWINGS: list[Edit] = [
    n_term,
    n_roster,
    n_budget,
    n_governance,
    n_data,
    n_outbound,
    n_tools,
    n_recovery,
    n_extension,
    n_escalation,
    n_delegation,
]


def narrow(raw: Raw, rnd: random.Random, steps: int) -> Raw:
    """``raw`` narrowed by ``steps`` random edits, each kept only if the result
    is a valid mandate."""
    current = copy.deepcopy(raw)
    for _ in range(steps):
        trial = copy.deepcopy(current)
        rnd.choice(NARROWINGS)(trial, rnd)
        try:
            parse(trial)
        except MalformedError:
            continue
        current = trial
    return current


seeds = st.integers(min_value=0, max_value=2**32 - 1)


@settings(max_examples=150, deadline=None, suppress_health_check=[HealthCheck.too_slow])
@given(seeds, st.integers(min_value=0, max_value=30))
def test_the_order_is_reflexive(seed: int, steps: int) -> None:
    mandate = parse(narrow(universe(), random.Random(seed), steps))
    assert refines(mandate, mandate) == ()


@settings(max_examples=150, deadline=None, suppress_health_check=[HealthCheck.too_slow])
@given(
    seeds,
    st.integers(min_value=0, max_value=30),
    st.integers(min_value=1, max_value=30),
    st.integers(min_value=1, max_value=30),
)
def test_every_narrowing_refines_and_the_order_is_transitive(
    seed: int, a: int, b: int, c: int
) -> None:
    rnd = random.Random(seed)
    grandparent = narrow(universe(), rnd, a)
    parent = narrow(grandparent, rnd, b)
    child = narrow(parent, rnd, c)
    g, p, k = parse(grandparent), parse(parent), parse(child)
    assert refines(p, g) == ()
    assert refines(k, p) == ()
    assert refines(k, g) == ()


