def _money(value: Decimal) -> str:
    return format(value.quantize(Decimal("0.00000001")), "f")


def _dec(text: str) -> Decimal:
    return Decimal(text)


def _spell(value: Decimal) -> str:
    """A decimal in its one spelling."""
    text = format(value.normalize(), "f")
    return text


